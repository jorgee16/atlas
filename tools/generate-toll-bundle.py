"""Generate the offline web bundle from the canonical Android tables."""
import json
from pathlib import Path
import sys
root = Path(__file__).resolve().parents[1]
tables = {p.stem: p.read_text(encoding='utf-8') for p in sorted((root/'android/native-app/src/main/assets/tolls').glob('*.csv'))}
content = '// Generated by tools/generate-toll-bundle.py; edit the canonical country CSVs.\nexport default '+json.dumps(tables, ensure_ascii=False, indent=2)+';\n'
charges = {p.stem: p.read_text(encoding='utf-8') for p in sorted((root/'android/native-app/src/main/assets/toll-charges').glob('*.csv'))}
content += 'export const fixedChargeTables = '+json.dumps(charges, ensure_ascii=False, indent=2)+';\n'
target = root/'src/routing/bundled-toll-tables.js'
if '--check' in sys.argv:
    if not target.exists() or target.read_text(encoding='utf-8') != content:
        raise SystemExit('Country toll bundle is stale: run python3 tools/generate-toll-bundle.py')
else:
    target.write_text(content, encoding='utf-8')
